class GuideScreen extends StatelessWidget {
  const GuideScreen({super.key});

  @override
  Widget build(BuildContext context) {
    final role = context.read<Session>().role;
    final key = switch (role) {
      'student' => 's',
      'teacher' || 'assistant' => 't',
      'staff' => 'f',
      _ => 'a',
    };
    final visible = _sections.where((s) => s.$2 == '*' || s.$2 == key || key == 'a');
    return Scaffold(
      appBar: AppBar(title: const Text('دليل الاستخدام')),
      body: ListView(padding: const EdgeInsets.all(12), children: [
        for (final s in visible)
          Card(
            child: ExpansionTile(
              initiallyExpanded: s.$2 == key,
              title: Text(s.$1, style: const TextStyle(fontWeight: FontWeight.bold)),
              childrenPadding: const EdgeInsets.fromLTRB(16, 0, 16, 12),
              children: [
                for (final item in s.$3)
                  Padding(
                    padding: const EdgeInsets.only(bottom: 10),
                    child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                      Text(item.$1, style: const TextStyle(fontWeight: FontWeight.w600)),
                      const SizedBox(height: 2),
                      Text(item.$2),
                    ]),
                  ),
              ],
            ),
          ),
      ]),
    );
  }
}
